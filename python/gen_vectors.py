"""
Writes ../vectors/vectors.json, the cross-language fixtures that both test suites check.

Deterministic outputs (sub-keys, contexts, normalization, blind indexes, seals, signatures) are
fully determined by the spec. Encrypted tokens and password hashes contain random nonces/salts, so
they are generated once and then fixed. Re-running this script replaces those fixtures; do that only
when the spec changes, and run both test suites afterwards.
"""

import base64
import json
import os
import sys
import tempfile

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from securekit import BlindIndexer, FieldCipher, RecordSealer, Signer, context, hash_password, normalize_text
from securekit._encoding import b64u_decode, b64u_encode
from securekit.uservault import UserVault
from securekit.vault import Vault
from tests.helpers import KEY_K1, KEY_K2, record_from_triples, ring

def b64_nopad(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii").rstrip("=")


OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "vectors", "vectors.json")
r = ring()


def main():
    vectors = {
        "_note": "TEST ONLY keys. Generated by python/gen_vectors.py; do not edit by hand. See SPEC.md.",
        "keyring": {"primary": "k2", "keys": {"k1": KEY_K1, "k2": KEY_K2}},
    }

    vectors["subkeys"] = [
        {"kid": kid, "purpose": purpose, "suffix": suffix, "hex": r.derive(kid, purpose, suffix).hex()}
        for kid in ("k1", "k2")
        for purpose, suffix in (("field", ""), ("seal", ""), ("sign", ""), ("blind", "5:users|5:email"))
    ]

    context_parts = [["users", "ssn", 42], ["é"], ["a|1:b"], ["ab", "c"], ["a", "bc"], ["日本語", -7], ["", 0]]
    vectors["context"] = [{"parts": parts, "expected": context(*parts)} for parts in context_parts]

    normalize_inputs = [
        "  Alice@Example.COM  ", "ＡＬＩＣＥ＠ｅｘａｍｐｌｅ．ｃｏｍ", "é", "É", "K", "ﬁ",
        " x　", "x ", "﻿a", "ß", "İ", "\t\n a b \r\n", "",
    ]
    vectors["normalize"] = [{"input": value, "expected": normalize_text(value)} for value in normalize_inputs]

    vectors["b64u"] = [
        {"hex": "", "encoded": "", "valid": True},
        {"hex": "00", "encoded": "AA", "valid": True},
        {"hex": "fbff", "encoded": "-_8", "valid": True},
        {"hex": "000102030405", "encoded": b64u_encode(bytes.fromhex("000102030405")), "valid": True},
    ] + [{"encoded": bad, "valid": False} for bad in ("A", "AB=", "AB+/", "AB", " AA", "AA\n", "A=", "é")]

    blind = BlindIndexer(r)
    blind8 = BlindIndexer(r, length_bytes=8)
    email = context("users", "email")
    vectors["blind"] = [
        {"value": "Alice@Example.com", "context": email, "mode": "text", "length": 16,
         "candidates": blind.candidates("Alice@Example.com", email)},
        {"value": "ＡＬＩＣＥ＠ｅｘａｍｐｌｅ．ｃｏｍ", "context": email, "mode": "text", "length": 16,
         "candidates": blind.candidates("ＡＬＩＣＥ＠ｅｘａｍｐｌｅ．ｃｏｍ", email)},
        {"value": "Alice@Example.com", "context": email, "mode": "exact", "length": 16,
         "candidates": blind.candidates("Alice@Example.com", email, mode="exact")},
        {"value": "Alice@Example.com", "context": email, "mode": "text", "length": 8,
         "candidates": blind8.candidates("Alice@Example.com", email)},
        {"value": "Alice@Example.com", "context": context("users", "recovery_email"), "mode": "text", "length": 16,
         "candidates": blind.candidates("Alice@Example.com", context("users", "recovery_email"))},
    ]

    sealer = RecordSealer(r)
    seal_cases = [
        ("basic", context("users", 42), [],
         [["id", "int", "42"], ["email", "str", "a@b.c"], ["password_hash", "str", "$argon2id$x"],
          ["active", "bool", True], ["note", "null", None], ["blob", "bytes", "00ff10"]]),
        ("edge values", "ctx", [],
         [["big", "int", "123456789012345678901234567890"], ["neg", "int", "-5"], ["zero", "int", "0"],
          ["empty", "str", ""], ["naïve", "str", "ü✓"], ["off", "bool", False], ["nobytes", "bytes", ""]]),
        ("excluded seal column", context("users", 1), ["row_seal"],
         [["id", "int", "1"], ["row_seal", "str", "sk1s.k2.whatever"], ["name", "str", "x"]]),
        ("empty record", "ctx", [], []),
    ]
    vectors["seal"] = [
        {"name": name, "context": ctx, "exclude": exclude, "record": triples,
         "seal": sealer.seal(record_from_triples(triples), ctx, exclude=exclude)}
        for name, ctx, exclude, triples in seal_cases
    ]

    signer = Signer(r)
    ts = 1_700_000_000
    vectors["sign"] = [
        {"body_hex": body.hex(), "timestamp": ts, "header": signer.sign(body, timestamp=ts)}
        for body in (b'{"event":"paid"}', "héllo".encode(), b"\x00\xff", b"")
    ]

    cipher = FieldCipher(r)
    ssn_ctx = context("users", "ssn", 1)
    fields = []
    for plaintext in ("123-45-6789 ✓".encode(), bytes(range(0, 256, 5)), b""):
        fields.append({"context": ssn_ctx, "plaintext_hex": plaintext.hex(), "token": cipher.encrypt(plaintext, ssn_ctx)})
    # a token written under the retired key k1 must still decrypt
    from securekit import Keyring
    old = FieldCipher(Keyring({"k1": KEY_K1}, "k1"))
    fields.append({"context": ssn_ctx, "plaintext_hex": b"written under k1".hex(), "token": old.encrypt(b"written under k1", ssn_ctx)})
    vectors["fields"] = fields

    good = fields[0]["token"]
    head, body = good.rsplit(".", 1)
    vectors["fields_invalid"] = [
        {"why": "wrong context", "context": context("users", "ssn", 2), "token": good},
        {"why": "tampered body", "context": ssn_ctx, "token": f"{head}.{body[:-2]}{'A' if body[-2] != 'A' else 'B'}{body[-1]}"},
        {"why": "relabelled key id", "context": ssn_ctx, "token": good.replace("sk1.k2.", "sk1.k1.")},
        {"why": "unknown key id", "context": ssn_ctx, "token": good.replace("sk1.k2.", "sk1.k9.")},
        {"why": "truncated", "context": ssn_ctx, "token": f"{head}.AAAA"},
        {"why": "wrong version", "context": ssn_ctx, "token": good.replace("sk1.", "sk2.", 1)},
    ]

    password = "pässwörd correct horse"
    vectors["passwords"] = [{
        "password": password,
        "hash": hash_password(password),
        "also_valid": ["pässwörd correct horse", "ｐässwörd correct horse"],
        "invalid": ["", "wrong", password + " "],
        # refused outright (limits / version / type / syntax), without running Argon2
        "invalid_hashes": [
            "$argon2id$v=19$m=4194304,t=3,p=4$" + b64_nopad(b"s" * 16) + "$" + b64_nopad(b"h" * 32),
            "$argon2id$v=19$m=65536,t=11,p=4$" + b64_nopad(b"s" * 16) + "$" + b64_nopad(b"h" * 32),
            "$argon2id$v=19$m=65536,t=3,p=17$" + b64_nopad(b"s" * 16) + "$" + b64_nopad(b"h" * 32),
            "$argon2id$v=16$m=65536,t=3,p=4$" + b64_nopad(b"s" * 16) + "$" + b64_nopad(b"h" * 32),
            "$argon2i$v=19$m=65536,t=3,p=4$" + b64_nopad(b"s" * 16) + "$" + b64_nopad(b"h" * 32),
            "$argon2id$v=19$m=65536,t=3,p=4$",
            "not a hash",
        ],
    }]

    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "vault.json")
        clock = lambda: 1_700_000_000  # noqa: E731
        vault = Vault.create(path, r, actor="gen", clock=clock)
        vault.put("payments/stripe_key", "sk_live_ünïcode-✓", retain=5)
        vault.put("db/password", "hunter2")
        vault.put("db/password", "hunter3")
        vault.destroy("db/password", 1)
        vault.put("binary/blob", bytes(range(0, 256, 17)))
        with open(path, encoding="utf-8") as handle:
            file_object = json.load(handle)
    vectors["vault"] = {
        "file": file_object,
        "active": [
            {"name": "payments/stripe_key", "version": 1, "value_hex": "sk_live_ünïcode-✓".encode().hex()},
            {"name": "db/password", "version": 2, "value_hex": b"hunter3".hex()},
            {"name": "binary/blob", "version": 1, "value_hex": bytes(range(0, 256, 17)).hex()},
        ],
        "destroyed": [{"name": "db/password", "version": 1}],
        "audit_actions": [e["action"] for e in file_object["audit"]],
    }

    passphrase = "pässwörd correct horse"
    user_vault, recovery_key = UserVault.create("user-42", passphrase, with_recovery=True)
    items = [("note-1", "my private note ✓".encode()), ("note-2", b"\x00\x01\x02")]
    vectors["uservault"] = {
        "user_id": "user-42",
        "passphrase": passphrase,
        "also_valid_passphrases": ["pässwörd correct horse"],
        "wrong_passphrases": ["wrong passphrase", passphrase + " "],
        "recovery_key": recovery_key,
        "state": user_vault.state,
        "items": [{"item_id": item_id, "plaintext_hex": data.hex(), "token": user_vault.encrypt_item(item_id, data)} for item_id, data in items],
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(vectors, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
